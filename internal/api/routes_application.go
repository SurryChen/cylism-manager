package api

import (
	applicationapi "github.com/cylism/cylism-manager/internal/api/application"
	authapi "github.com/cylism/cylism-manager/internal/api/auth"
	auditservice "github.com/cylism/cylism-manager/internal/service/audit"
	"github.com/gin-gonic/gin"
)

func registerApplicationRoutes(r *gin.Engine, apiGroup *gin.RouterGroup, h *applicationapi.ApplicationHandler, jwtSecret []byte, audit gin.HandlerFunc, auditLogs auditservice.Repository) {
	projects := apiGroup.Group("/projects")
	projects.GET("", h.ListProjects)
	projects.POST("", h.CreateProject)
	projects.PUT("/:projectID", h.UpdateProject)
	projects.DELETE("/:projectID", h.DeleteProject)
	projects.GET("/:projectID/environments", h.ListEnvironments)
	projects.GET("/environments/namespace-conflicts", h.ListEnvironmentNamespaceConflicts)
	projects.POST("/:projectID/environments", h.CreateEnvironment)
	projects.PUT("/:projectID/environments/:environmentID", h.UpdateEnvironment)
	projects.POST("/:projectID/environments/:environmentID/sync-namespace", h.HandleEnvironment((*applicationapi.ApplicationHandler).SyncEnvironmentNamespace))
	projects.DELETE("/:projectID/environments/:environmentID", h.DeleteEnvironment)

	catalog := apiGroup.Group("/application-catalog")
	catalog.GET("", h.ListCatalogItems)
	catalog.GET("/:catalogID", h.GetCatalogItem)
	catalog.GET("/installations", h.ListCatalogInstallations)
	catalog.POST("", h.CreateCatalogItem)
	catalog.POST("/from-environment", h.CreateCatalogFromEnvironment)
	catalog.PUT("/:catalogID", h.UpdateCatalogItem)
	catalog.DELETE("/:catalogID", h.DeleteCatalogItem)
	catalog.POST("/import", h.ImportCatalogItems)

	applications := apiGroup.Group("/applications")
	applications.GET("", h.ListApplications)
	applications.GET("/discovery", h.DiscoverApplications)
	applications.POST("", h.CreateApplication)
	applications.DELETE("/:id", h.DeleteApplication)
	applications.GET("/:id", h.GetApplication)
	applications.PUT("/:id/capabilities", h.UpdateCapabilities)
	applications.GET("/:id/managed-files", h.ListManagedFiles)
	applications.POST("/:id/delegations", h.CreateDelegation)
	applications.POST("/:id/integration-handoffs", h.CreateIntegrationHandoff)
	applications.PUT("/:id/workload-kind", h.HandleApplication((*applicationapi.ApplicationHandler).UpdateWorkloadKind))
	applications.GET("/:id/runtime", h.HandleApplication((*applicationapi.ApplicationHandler).GetApplicationRuntime))
	applications.GET("/:id/pods", h.HandleApplication((*applicationapi.ApplicationHandler).ListApplicationPods))
	applications.GET("/:id/pods/:pod/logs", h.HandleApplication((*applicationapi.ApplicationHandler).GetApplicationPodLogs))
	applications.GET("/:id/deployment-templates", h.ListDeploymentTemplates)
	applications.POST("/:id/deployment-templates", h.HandleApplication((*applicationapi.ApplicationHandler).CreateDeploymentTemplate))
	applications.GET("/:id/deployment-templates/:templateID", h.GetDeploymentTemplate)
	applications.PUT("/:id/deployment-templates/:templateID", h.HandleApplication((*applicationapi.ApplicationHandler).UpdateDeploymentTemplate))
	applications.DELETE("/:id/deployment-templates/:templateID", h.DeleteDeploymentTemplate)
	applications.POST("/:id/deployment-templates/:templateID/default", h.SetDefaultDeploymentTemplate)
	applications.GET("/:id/endpoints", h.ListApplicationEndpoints)
	applications.POST("/:id/endpoints", h.HandleApplication((*applicationapi.ApplicationHandler).CreateApplicationEndpoint))
	applications.PUT("/:id/endpoints/:endpointID", h.HandleApplication((*applicationapi.ApplicationHandler).UpdateApplicationEndpoint))
	applications.DELETE("/:id/endpoints/:endpointID", h.HandleApplication((*applicationapi.ApplicationHandler).DeleteApplicationEndpoint))
	applications.POST("/:id/releases", h.HandleApplication((*applicationapi.ApplicationHandler).CreateRelease))
	applications.GET("/:id/deploy-webhook", h.DeployWebhookStatus)
	applications.POST("/:id/deploy-webhook/secret", h.GenerateDeployWebhookSecret)
	applications.DELETE("/:id/deploy-webhook", h.DisableDeployWebhook)
	applications.POST("/:id/releases/preflight", h.HandleApplication((*applicationapi.ApplicationHandler).PreflightRelease))
	applications.POST("/:id/restarts", h.HandleApplication((*applicationapi.ApplicationHandler).RestartApplication))
	applications.GET("/:id/releases/:releaseID", h.HandleApplication((*applicationapi.ApplicationHandler).GetRelease))
	applications.POST("/:id/releases/:releaseID/retry", h.HandleApplication((*applicationapi.ApplicationHandler).RetryRelease))
	applications.POST("/:id/releases/:releaseID/rollback", h.HandleApplication((*applicationapi.ApplicationHandler).RollbackRelease))

	integration := r.Group("/api/integrations/applications")
	integration.Use(authapi.DelegationAuthMiddlewareWithAudit(jwtSecret, auditLogs), audit)
	integration.GET("/discovery", h.IntegrationDiscoverApplications)
	integration.GET("/:id/runtime", h.HandleApplication((*applicationapi.ApplicationHandler).IntegrationGetApplicationRuntime))
	integration.GET("/:id/configmaps", h.IntegrationListManagedConfigMaps)
	integration.GET("/:id/configmaps/:configMapID", h.IntegrationGetManagedConfigMap)
	integration.PUT("/:id/configmaps/:configMapID", h.HandleApplication((*applicationapi.ApplicationHandler).IntegrationReplaceManagedConfigMap))
	integration.GET("/:id/hysteria/config", h.IntegrationHysteriaConfig)
	integration.GET("/:id/hysteria/users/:username/credential", h.IntegrationHysteriaCredential)
	integration.PUT("/:id/hysteria/users/:username", h.HandleApplication((*applicationapi.ApplicationHandler).IntegrationUpdateHysteriaUser))
	integration.POST("/:id/restarts", h.HandleApplication((*applicationapi.ApplicationHandler).IntegrationRestartApplication))
	integration.GET("/:id/releases/:releaseID", h.HandleApplication((*applicationapi.ApplicationHandler).IntegrationGetRelease))

	sessions := r.Group("/api/integrations/sessions")
	sessions.POST("/exchange", h.ExchangeIntegrationSession)
	sessions.POST("/delegation", h.CreateIntegrationDelegation)
	r.POST("/api/applications/:id/deployments", h.DeployWebhook)

	apiGroup.GET("/workspace/overview", h.HandleWorkspace((*applicationapi.ApplicationHandler).WorkspaceOverview))
}
