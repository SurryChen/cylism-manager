import { api } from './index.js'

const base = '/cloud/databases'
const segment = value => encodeURIComponent(String(value))

const clusterBase = '/cloud/mysql-clusters'
export const getMySQLClusters = () => api.get(clusterBase)
export const createMySQLCluster = payload => api.post(clusterBase, payload)
export const getMySQLCluster = id => api.get(`${clusterBase}/${segment(id)}`)
export const getMySQLClusterNodes = id => api.get(`${clusterBase}/${segment(id)}/nodes`)
export const updateMySQLClusterResourcePool = (id, databaseNodes) => api.put(`${clusterBase}/${segment(id)}/resource-pool`, { database_nodes: databaseNodes })
export const getMySQLClusterRuntime = id => api.get(`${clusterBase}/${segment(id)}/runtime`)
export const getMySQLClusterConfig = id => api.get(`${clusterBase}/${segment(id)}/config`)
export const updateMySQLClusterConfig = (id, mycnf) => api.put(`${clusterBase}/${segment(id)}/config`, { mycnf })
export const restartMySQLClusterForConfig = id => api.post(`${clusterBase}/${segment(id)}/config/restart`, {})
export const preflightMySQLCluster = (id, payload) => api.post(`${clusterBase}/${segment(id)}/preflight`, payload)
export const retryMySQLClusterPod = (id, podName) => api.post(`${clusterBase}/${segment(id)}/pods/${segment(podName)}/retry`, {})
export const pullMySQLClusterPodImages = (id, podName) => api.post(`${clusterBase}/${segment(id)}/pods/${segment(podName)}/pull-images`, {})
export const getMySQLClusterTasks = (id, { limit = 10, offset = 0 } = {}) => api.get(`${clusterBase}/${segment(id)}/tasks?limit=${limit}&offset=${offset}`)
export const getMySQLClusterTaskLogs = (id, taskID) => api.get(`${clusterBase}/${segment(id)}/tasks/${segment(taskID)}/logs`)
export const switchMySQLClusterPrimary = (id, podName) => api.post(`${clusterBase}/${segment(id)}/primary`, { pod_name: podName })
export const pauseMySQLClusterDeployment = id => api.post(`${clusterBase}/${segment(id)}/deployment/pause`, {})
export const retryMySQLClusterShutdown = id => api.post(`${clusterBase}/${segment(id)}/deployment/retry-shutdown`, {})
export const getMySQLClusterCleanup = id => api.get(`${clusterBase}/${segment(id)}/deployment/cleanup`)
export const cleanupMySQLCluster = (id, resourceName, deleteClaims = false) => api.post(`${clusterBase}/${segment(id)}/deployment/cleanup`, { confirm_resource_name: resourceName, delete_claims: deleteClaims })
export const getMySQLOperator = id => api.get(`${clusterBase}/${segment(id)}/operator`)
export const installMySQLOperator = id => api.post(`${clusterBase}/${segment(id)}/operator/install`, {})
export const cancelMySQLOperator = id => api.post(`${clusterBase}/${segment(id)}/operator/cancel`, {})
export const uninstallMySQLOperator = id => api.post(`${clusterBase}/${segment(id)}/operator/uninstall`, {})
export const deployMySQLCluster = (id, payload) => api.put(`${clusterBase}/${segment(id)}/topology`, payload)
export const addMySQLClusterInstance = (id, data = {}) => api.post(`${clusterBase}/${segment(id)}/instances`, data)
export const addMySQLClusterRouter = (id, data = {}) => api.post(`${clusterBase}/${segment(id)}/routers`, data)
export const retireMySQLClusterRouter = id => api.post(`${clusterBase}/${segment(id)}/routers/scale-down`, {})
export const repairMySQLClusterRouterPlacement = id => api.post(`${clusterBase}/${segment(id)}/routers/repair-placement`, {})
export const deleteMySQLCluster = id => api.delete(`${clusterBase}/${segment(id)}`)

export const getDatabases = () => api.get(base)
export const createDatabase = payload => api.post(base, payload)
export const inspectDatabase = id => api.get(`${base}/${segment(id)}`)
export const reconcileDatabase = id => api.post(`${base}/${segment(id)}/reconcile`, {})
export const deleteDatabase = id => api.delete(`${base}/${segment(id)}`)
export const getDatabaseBindings = id => api.get(`${base}/${segment(id)}/bindings`)
export const bindDatabase = (id, payload) => api.post(`${base}/${segment(id)}/bindings`, payload)
export const unbindDatabase = (id, bindingID) => api.delete(`${base}/${segment(id)}/bindings/${segment(bindingID)}`)
